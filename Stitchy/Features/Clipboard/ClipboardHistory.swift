import AppKit
import Observation

/// Opt-in clipboard history.
///
/// macOS has no "pasteboard changed" notification, so while enabled Stitchy
/// checks `NSPasteboard.general.changeCount` (a cheap integer read, no
/// contents) twice a second and reads the contents only when it changes.
/// Never recorded:
///  - items marked concealed or transient (org.nspasteboard.ConcealedType /
///    TransientType, used by password managers),
///  - copies made while an excluded app is frontmost,
///  - anything while the feature is off.
/// History lives in memory only and is gone when Stitchy quits.
/// On macOS 15.4+ the system may ask once whether Stitchy may read the
/// pasteboard; that choice is respected.
@MainActor @Observable
final class ClipboardHistory {
    struct Entry: Identifiable, Equatable {
        enum Content: Equatable {
            case text(String)
            case files([URL])
            case image(NSImage)
        }
        let id = UUID()
        let date = Date()
        let content: Content
        let sourceApp: String?
        var pinned = false

        /// Recognised kinds of text that get a one-tap action.
        enum Smart: Equatable { case link(URL), color(NSColor), email(String) }
        var smart: Smart? {
            guard case .text(let raw) = content else { return nil }
            let t = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if t.range(of: #"^#?([0-9a-fA-F]{6})$"#, options: .regularExpression) != nil,
               let v = UInt32(t.replacingOccurrences(of: "#", with: ""), radix: 16) {
                return .color(NSColor(srgbRed: CGFloat((v >> 16) & 0xff) / 255, green: CGFloat((v >> 8) & 0xff) / 255, blue: CGFloat(v & 0xff) / 255, alpha: 1))
            }
            if t.range(of: #"^[^@\s]+@[^@\s]+\.[a-zA-Z]{2,}$"#, options: .regularExpression) != nil { return .email(t) }
            if !t.contains(" "), let url = URL(string: t), let scheme = url.scheme, ["http", "https"].contains(scheme), url.host != nil { return .link(url) }
            return nil
        }

        var preview: String {
            switch content {
            case .text(let s): s.trimmingCharacters(in: .whitespacesAndNewlines)
            case .files(let urls): urls.map(\.lastPathComponent).joined(separator: ", ")
            case .image: "Image"
            }
        }

        var symbol: String {
            switch content {
            case .text(let s): s.hasPrefix("http") ? "link" : Self.looksLikeCode(s) ? "chevron.left.forwardslash.chevron.right" : "doc.plaintext"
            case .files: "doc.on.doc"
            case .image: "photo"
            }
        }

        /// Heuristic: several lines, or code punctuation/keywords. Used for the icon
        /// and monospaced preview only, so a wrong guess is harmless.
        nonisolated static func looksLikeCode(_ text: String) -> Bool {
            let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
            guard t.count >= 8, !t.hasPrefix("http") else { return false }
            let signals = [#"[{};]\s*$"#, #"^\s*(func|let|var|const|def|class|import|return|if|for|while|#include|public|private|SELECT|<\w+[ >])\b"#,
                           #"=>|->|::|\(\)|!=|==|&&|\|\|"#, #"^\s{2,}\S"#]
            let hits = signals.filter { t.range(of: "(?m)" + $0, options: .regularExpression) != nil }.count
            return hits >= 2
        }

        var isCode: Bool { if case .text(let s) = content { Self.looksLikeCode(s) } else { false } }

        static func == (a: Entry, b: Entry) -> Bool { a.id == b.id }
    }

    private(set) var entries: [Entry] = []
    private(set) var isRunning = false
    @ObservationIgnored private let settings: AppSettings
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var ownWriteChange: Int?

    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    init(settings: AppSettings) { self.settings = settings }

    func start() {
        guard timer == nil else { return }
        isRunning = true
        lastChange = NSPasteboard.general.changeCount  // never import what was copied before opting in
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer?.tolerance = 0.25
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        isRunning = false
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        if lastChange == ownWriteChange { return }
        let frontmost = NSWorkspace.shared.frontmostApplication
        if let id = frontmost?.bundleIdentifier, settings.clipboardExcludedApps.contains(id) { return }
        let types = pasteboard.types ?? []
        if settings.clipboardIgnoreConcealed,
           types.contains(Self.concealed) || types.contains(Self.transient) || types.contains(Self.autoGenerated) { return }

        let content: Entry.Content
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(String(text.prefix(20_000)))
        } else if let image = NSImage(pasteboard: pasteboard) {
            content = .image(image)
        } else {
            return
        }
        record(Entry(content: content, sourceApp: frontmost?.localizedName))
    }

    /// Adds an entry, moving an identical earlier copy to the top. Exposed for tests.
    func record(_ entry: Entry) {
        islandLog.info("clipboard recorded \(entry.symbol, privacy: .public)")
        var entry = entry
        if let existing = entries.first(where: { $0.content == entry.content }) { entry.pinned = existing.pinned }
        entries.removeAll { $0.content == entry.content }
        entries.insert(entry, at: 0)
        trim()
    }

    /// Pinned entries never count against the limit and survive Clear.
    private func trim() {
        let limit = max(1, Int(settings.clipboardHistorySize))
        var unpinned = 0
        entries = entries.filter { e in
            if e.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
    }

    func togglePin(_ entry: Entry) {
        guard let i = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[i].pinned.toggle()
        trim()
    }

    func search(_ query: String) -> [Entry] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let sorted = entries.filter(\.pinned) + entries.filter { !$0.pinned }
        return q.isEmpty ? sorted : sorted.filter { $0.preview.localizedCaseInsensitiveContains(q) || ($0.sourceApp ?? "").localizedCaseInsensitiveContains(q) }
    }

    /// Puts an entry back on the clipboard. Not re-recorded as a new copy.
    func copy(_ entry: Entry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.content {
        case .text(let s): pasteboard.setString(s, forType: .string)
        case .files(let urls): pasteboard.writeObjects(urls as [NSURL])
        case .image(let image): pasteboard.writeObjects([image])
        }
        ownWriteChange = pasteboard.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(entry, at: 0)
    }

    func delete(_ entry: Entry) { entries.removeAll { $0.id == entry.id } }
    /// Removes everything except pinned entries.
    func clear() { entries.removeAll { !$0.pinned } }
}
